# =============================================================================
# Combined Registry
# =============================================================================

FEATURE_TYPES: Final[dict[str, FeatureType]] = {
    **METADATA_FEATURE_TYPES,
    **TEXT_FEATURE_TYPES,
    **STATISTICAL_FEATURE_TYPES,
    **REGEX_FEATURE_TYPES,
}

# =============================================================================
# Validation
# =============================================================================

_missing = set(FEATURE_NAMES) - set(FEATURE_TYPES.keys())
_extra = set(FEATURE_TYPES.keys()) - set(FEATURE_NAMES)

if _missing:
    raise RuntimeError(
        f"Missing feature type definitions: {sorted(_missing)}"
    )

if _extra:
    raise RuntimeError(
        f"Unknown feature type definitions: {sorted(_extra)}"
    )