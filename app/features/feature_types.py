from enum import Enum
from typing import Final

from app.features.feature_names import FEATURE_NAMES


# =============================================================================
# Feature Types
# =============================================================================


class FeatureType(str, Enum):
    """
    Supported feature datatypes.
    """

    NUMERIC = "numeric"
    BOOLEAN = "boolean"
    CATEGORICAL = "categorical"


# =============================================================================
# Metadata Features
# =============================================================================

